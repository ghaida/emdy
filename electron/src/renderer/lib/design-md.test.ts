import { describe, it, expect } from 'vitest';
import { parseDesignMd, isValidCssColor, cssLength } from './design-md';
import { categoriesForHeading, buildInjectionMap, type DesignTokens } from './design-md';

const HERITAGE = `---
name: Heritage
description: A warm editorial identity
colors:
  primary: "#1A1C1E"
  tertiary: "#B8422E"
typography:
  h1:
    fontFamily: Public Sans
    fontSize: 3rem
spacing:
  sm: 8px
  md: 16px
rounded:
  sm: 4px
---

## Overview

Body text here.
`;

describe('parseDesignMd detection', () => {
  it('recognizes a design.md whose front matter follows an HTML comment', () => {
    const result = parseDesignMd('<!-- generated by a tool -->\n' + HERITAGE);
    expect(result?.tokens.name).toBe('Heritage');
    expect(result?.body).toContain('## Overview');
  });

  it('parses a valid design.md file', () => {
    const result = parseDesignMd(HERITAGE);
    expect(result).not.toBeNull();
    expect(result!.source).toBe('front-matter');
    expect(result!.tokens.name).toBe('Heritage');
    expect(result!.tokens.description).toBe('A warm editorial identity');
    expect(result!.tokens.colors).toEqual({ primary: '#1A1C1E', tertiary: '#B8422E' });
    expect(result!.body).not.toContain('---');
    expect(result!.body).toContain('## Overview');
  });

  it('returns null when there is no front matter', () => {
    expect(parseDesignMd('# Just a doc\n\nHello.')).toBeNull();
  });

  it('returns null for blog-style front matter (no token categories)', () => {
    expect(parseDesignMd('---\ntitle: My Post\ndate: 2026-01-01\nname: x\n---\nBody')).toBeNull();
  });

  it('returns null when name is missing', () => {
    expect(parseDesignMd('---\ncolors:\n  primary: "#fff"\n---\nBody')).toBeNull();
  });

  it('returns null when name is not a string', () => {
    expect(parseDesignMd('---\nname: 42\ncolors:\n  primary: "#fff"\n---\nBody')).toBeNull();
  });

  it('returns null when the only token category is empty', () => {
    expect(parseDesignMd('---\nname: X\ncolors: {}\n---\nBody')).toBeNull();
  });

  it('returns null on malformed YAML instead of throwing', () => {
    expect(parseDesignMd('---\nname: [unclosed\ncolors: {\n---\nBody')).toBeNull();
  });

  it('returns null when front matter is not a mapping', () => {
    expect(parseDesignMd('---\n- just\n- a list\n---\nBody')).toBeNull();
  });

  it('accepts a file with front matter only and empty body', () => {
    const result = parseDesignMd('---\nname: X\ncolors:\n  a: "#fff"\n---\n');
    expect(result).not.toBeNull();
    expect(result!.body.trim()).toBe('');
  });

  it('handles CRLF line endings', () => {
    const result = parseDesignMd('---\r\nname: X\r\ncolors:\r\n  a: "#fff"\r\n---\r\nBody');
    expect(result).not.toBeNull();
    expect(result!.body).toContain('Body');
  });

  it('detects a file that starts with a UTF-8 BOM (F3)', () => {
    const result = parseDesignMd('﻿---\nname: X\ncolors:\n  a: "#fff"\n---\nBody');
    expect(result).not.toBeNull();
    expect(result!.tokens.name).toBe('X');
    expect(result!.body).toContain('Body');
  });

  it('returns null quickly for oversized front matter without parsing YAML (F8)', () => {
    const huge = 'x'.repeat(200 * 1024);
    const content = `---\nname: X\ncolors:\n  a: "#fff"\n  big: "${huge}"\n---\nBody`;
    const start = Date.now();
    const result = parseDesignMd(content);
    const elapsed = Date.now() - start;
    expect(result).toBeNull();
    expect(elapsed).toBeLessThan(1000);
  });
});

describe('parseDesignMd normalization', () => {
  it('coerces numeric spacing values to strings', () => {
    const r = parseDesignMd('---\nname: X\nspacing:\n  sm: 8\n  md: 16px\n---\n');
    expect(r!.tokens.spacing).toEqual({ sm: '8', md: '16px' });
  });

  it('keeps only known typography fields, coerced to strings', () => {
    const r = parseDesignMd(
      '---\nname: X\ntypography:\n  h1:\n    fontFamily: Public Sans\n    fontSize: 3rem\n    fontWeight: 600\n    bogus: nope\n---\n'
    );
    expect(r!.tokens.typography!.h1).toEqual({
      fontFamily: 'Public Sans',
      fontSize: '3rem',
      fontWeight: '600',
    });
  });

  it('drops non-object typography entries', () => {
    const r = parseDesignMd('---\nname: X\ntypography:\n  h1: big\ncolors:\n  a: "#fff"\n---\n');
    expect(r!.tokens.typography).toBeUndefined();
  });

  it('resolves token references in components', () => {
    const r = parseDesignMd(
      '---\nname: X\ncolors:\n  primary: "#1A1C1E"\ncomponents:\n  button:\n    backgroundColor: "{colors.primary}"\n    padding: 12px\n---\n'
    );
    expect(r!.tokens.components!.button).toEqual({
      backgroundColor: '#1A1C1E',
      padding: '12px',
    });
  });

  it('resolves chained references', () => {
    const r = parseDesignMd(
      '---\nname: X\ncolors:\n  base: "#fff"\n  surface: "{colors.base}"\ncomponents:\n  card:\n    bg: "{colors.surface}"\n---\n'
    );
    expect(r!.tokens.components!.card.bg).toBe('#fff');
  });

  it('keeps unresolvable references literal', () => {
    const r = parseDesignMd(
      '---\nname: X\ncolors:\n  a: "#fff"\ncomponents:\n  card:\n    bg: "{colors.missing}"\n---\n'
    );
    expect(r!.tokens.components!.card.bg).toBe('{colors.missing}');
  });

  it('keeps circular references literal instead of hanging', () => {
    const r = parseDesignMd(
      '---\nname: X\ncolors:\n  a: "{colors.b}"\n  b: "{colors.a}"\n---\n'
    );
    expect(r!.tokens.colors!.a).toBe('{colors.b}');
  });

  // F2: a chain of N reference edges from the component value to the final
  // literal. MAX_REFERENCE_HOPS is 8, so up to 8 edges must fully resolve.
  const chainFrontMatter = (edges: number): string => {
    // component.card.bg -> colors.c0 -> colors.c1 -> ... -> colors.c{edges-2} -> "#fff"
    // That is `edges` dereferences total (bg->c0 is edge 1, ..., c{edges-2}->#fff is the last).
    const lines: string[] = ['---', 'name: X', 'colors:'];
    for (let i = 0; i < edges - 1; i++) lines.push(`  c${i}: "{colors.c${i + 1}}"`);
    lines.push(`  c${edges - 1}: "#fff"`);
    lines.push('components:', '  card:', '    bg: "{colors.c0}"', '---', '');
    return lines.join('\n');
  };

  it('resolves a 7-edge reference chain to the final value', () => {
    const r = parseDesignMd(chainFrontMatter(7));
    expect(r!.tokens.components!.card.bg).toBe('#fff');
  });

  it('resolves an 8-edge reference chain to the final value (was off-by-one)', () => {
    const r = parseDesignMd(chainFrontMatter(8));
    expect(r!.tokens.components!.card.bg).toBe('#fff');
  });

  it('keeps a 9-edge reference chain literal (beyond the cap)', () => {
    const r = parseDesignMd(chainFrontMatter(9));
    expect(r!.tokens.components!.card.bg).toBe('{colors.c0}');
  });
});

describe('isValidCssColor', () => {
  it('accepts hex, rgb, and oklch', () => {
    expect(isValidCssColor('#B8422E')).toBe(true);
    expect(isValidCssColor('rgb(10, 20, 30)')).toBe(true);
    expect(isValidCssColor('oklch(62% 0.18 250)')).toBe(true);
  });
  it('rejects non-color strings', () => {
    expect(isValidCssColor('{colors.missing}')).toBe(false);
    expect(isValidCssColor('12px')).toBe(false);
  });
});

describe('cssLength', () => {
  it('converts px, rem, em, and bare numbers to px', () => {
    expect(cssLength('16px')).toBe(16);
    expect(cssLength('1.5rem')).toBe(24);
    expect(cssLength('2em')).toBe(32);
    expect(cssLength('8')).toBe(8);
  });
  it('returns null for unparseable or negative values', () => {
    expect(cssLength('auto')).toBeNull();
    expect(cssLength('-4px')).toBeNull();
  });
  it('matches units case-insensitively (F4)', () => {
    expect(cssLength('12PX')).toBe(12);
    expect(cssLength('1.5REM')).toBe(24);
    expect(cssLength('2Em')).toBe(32);
  });
  it('rejects multi-dot numbers (F4)', () => {
    expect(cssLength('1.2.3')).toBeNull();
    expect(cssLength('1.2.3px')).toBeNull();
  });
  it('accepts leading-dot decimals (F4 amendment)', () => {
    expect(cssLength('.5rem')).toBe(8);
    expect(cssLength('.5px')).toBe(0.5);
    expect(cssLength('.25em')).toBe(4);
  });
});

describe('categoriesForHeading', () => {
  it('maps spec section names and aliases', () => {
    expect(categoriesForHeading('Colors')).toEqual(['colors']);
    expect(categoriesForHeading('typography')).toEqual(['typography']);
    expect(categoriesForHeading('Layout')).toEqual(['spacing']);
    expect(categoriesForHeading('Layout & Spacing')).toEqual(['spacing']);
    expect(categoriesForHeading('Spacing')).toEqual(['spacing']);
    expect(categoriesForHeading('Shapes')).toEqual(['rounded']);
    expect(categoriesForHeading('Components:')).toEqual(['components']);
  });
  it('returns nothing for non-token sections', () => {
    expect(categoriesForHeading('Overview')).toEqual([]);
    expect(categoriesForHeading("Do's and Don'ts")).toEqual([]);
    expect(categoriesForHeading('Elevation & Depth')).toEqual([]);
    expect(categoriesForHeading('Random Section')).toEqual([]);
  });
  it('ignores numbering and a subtitle after a colon', () => {
    expect(categoriesForHeading('2. Colors')).toEqual(['colors']);
    expect(categoriesForHeading('2. Colors: The Print Palette')).toEqual(['colors']);
    expect(categoriesForHeading('3) Typography')).toEqual(['typography']);
    expect(categoriesForHeading('4.1 Layout')).toEqual(['spacing']);
    expect(categoriesForHeading('Overview: Colors and Type')).toEqual([]);
  });
  it('treats Theme and Palette sections as colors', () => {
    expect(categoriesForHeading('Theme')).toEqual(['colors']);
    expect(categoriesForHeading('Palette')).toEqual(['colors']);
    expect(categoriesForHeading('2. Color Palette & Roles')).toEqual(['colors']);
    expect(categoriesForHeading('1. Theme delivery')).toEqual([]);
  });
  it('finds sections named after a dash or alongside others', () => {
    expect(categoriesForHeading('Tokens — Colors')).toEqual(['colors']);
    expect(categoriesForHeading('Tokens — Spacing & Shapes')).toEqual(['spacing', 'rounded']);
    expect(categoriesForHeading('4. Elevation, Shape, and Motion')).toEqual(['rounded']);
    expect(categoriesForHeading('Colour')).toEqual(['colors']);
    expect(categoriesForHeading('Color-blind safety')).toEqual([]);
  });
});

describe('buildInjectionMap', () => {
  const tokens: DesignTokens = {
    name: 'X',
    colors: { a: '#fff' },
    spacing: { sm: '8px' },
  };

  it('maps first matching heading line per category', () => {
    const body = '## Overview\n\ntext\n\n## Colors\n\ntext\n\n## Layout\n\ntext\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.get(5)).toEqual(['colors']);
    expect(map.get(9)).toEqual(['spacing']);
    expect(map.size).toBe(2);
  });

  it('claims numbered headings with subtitles', () => {
    const body = '## 1. Overview\n\n## 2. Colors: The Print Palette\n\n## 4. Layout\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.get(3)).toEqual(['colors']);
    expect(map.get(5)).toEqual(['spacing']);
    expect(map.size).toBe(2);
  });

  it('gives a heading every category it names', () => {
    const map = buildInjectionMap('## Tokens — Spacing & Shapes\n', { ...tokens, rounded: { sm: '4px' } });
    expect(map.get(1)).toEqual(['spacing', 'rounded']);
  });

  it('ignores headings for categories the file has no tokens for', () => {
    const map = buildInjectionMap('## Typography\n\n## Colors\n', tokens);
    expect(map.size).toBe(1);
    expect(map.get(3)).toEqual(['colors']);
  });

  it('only the first matching heading per category is used', () => {
    const map = buildInjectionMap('## Colors\n\n## Colors\n', tokens);
    expect(map.size).toBe(1);
    expect(map.get(1)).toEqual(['colors']);
  });

  it('skips headings inside fenced code blocks', () => {
    const body = '```\n## Colors\n```\n\n## Colors\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(1);
    expect(map.get(5)).toEqual(['colors']);
  });

  // F1: fence handling must match CommonMark, not a naive line toggle.
  it('does not claim a heading when a ~~~ line sits inside a ``` block (mixed markers)', () => {
    const body = '```\n~~~\n## Colors\n```\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(0);
  });

  it('does not claim a heading inside a 3-space-indented fence opener', () => {
    const body = '   ```\n## Colors\n   ```\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(0);
  });

  it('does not claim a heading inside a 4-backtick fence with a 3-backtick line inside', () => {
    const body = '````\n```\n## Colors\n````\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(0);
  });

  // F5: real headings the naive scanner missed.
  it('claims a setext-style h2 (text + dashed underline)', () => {
    const body = 'Colors\n------\n\ntext\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(1);
    expect(map.get(1)).toEqual(['colors']);
  });

  it('claims a 1-3-space-indented ATX h2', () => {
    const body = '  ## Colors\n\ntext\n';
    const map = buildInjectionMap(body, tokens);
    expect(map.size).toBe(1);
    expect(map.get(1)).toEqual(['colors']);
  });
});
